def __getattr__(name: str):
    if name == "concurrency":
        from . import concurrency

        globals()["concurrency"] = concurrency
        return concurrency
    return lazy_import(name, _LAZY_MAP, __name__, globals())


def __dir__() -> list[str]:
    return sorted(set(globals()) | set(__all__) | {"concurrency"})


