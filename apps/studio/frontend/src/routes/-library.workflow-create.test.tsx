// TanStack Router's Vite plugin materializes this test-only split module; it
// has no source declaration for TypeScript to resolve.
// @ts-expect-error virtual module generated by @tanstack/router-plugin
const { component: LibraryPage } = await import("./library.tsx?tsr-split=component");

interface Deferred<T> {
  promise: Promise<T>;
  resolve: (value: T) => void;
  reject: (reason: unknown) => void;
}

function deferred<T>(): Deferred<T> {
  let resolve!: (value: T) => void;
  let reject!: (reason: unknown) => void;
  const promise = new Promise<T>((resolvePromise, rejectPromise) => {
    resolve = resolvePromise;
    reject = rejectPromise;
  });
  return { promise, resolve, reject };
}

async function flush() {
  await act(async () => {
    await Promise.resolve();
    await Promise.resolve();
    await Promise.resolve();
  });
}

describe("Library workflow creation identity", () => {
  let container: HTMLDivElement;
  let root: Root;

  beforeEach(() => {
    vi.stubGlobal("IS_REACT_ACT_ENVIRONMENT", true);
    Object.values(api).forEach((mock) => mock.mockReset());
    router.search = {};
    router.navigate.mockReset();
    router.navigate.mockImplementation(
      ({
        search,
      }: {
        search: (previous: Record<string, string | undefined>) => typeof router.search;
      }) => {
        router.search = search(router.search);
        return Promise.resolve();
      },
    );

    api.listAgents.mockResolvedValue({ agents: [] });
    api.listBuiltinPlaybooks.mockResolvedValue({ playbooks: [] });
    api.listPlaybooks.mockResolvedValue({ playbooks: [] });
    api.listSkills.mockResolvedValue({ skills: [] });
    api.listPlugins.mockResolvedValue({ plugins: [] });
    api.listEngineDefs.mockResolvedValue([]);
    api.listMcpServers.mockResolvedValue({ servers: [] });

    container = document.createElement("div");
    document.body.appendChild(container);
    root = createRoot(container);
  });

  afterEach(() => {
    act(() => root.unmount());
    container.remove();
    vi.unstubAllGlobals();
  });

  async function createWhileReloadIsPending(reload: Deferred<unknown[]>) {
    api.listWorkflowDefs.mockResolvedValueOnce([]).mockReturnValueOnce(reload.promise);

    await act(async () => {
      root.render(<LibraryPage />);
    });
    await flush();

    const newButton = [...container.querySelectorAll("button")].find((button) =>
      button.textContent?.includes("newWorkflow"),
    );
    expect(newButton).toBeDefined();
    await act(async () => newButton?.click());

    const completeButton = container.querySelector<HTMLButtonElement>(
      '[data-testid="complete-create"]',
    );
    expect(completeButton).not.toBeNull();
    await act(async () => completeButton?.click());
    await flush();
  }

  it("uses the returned id for detail while the catalog reload is delayed", async () => {
    const reload = deferred<unknown[]>();
    await createWhileReloadIsPending(reload);

    expect(router.search.sel).toBe(`workflow:${createdWorkflow.name}`);
    expect(
      container.querySelector<HTMLElement>('[data-testid="workflow-detail"]')?.dataset.workflowId,
    ).toBe(createdWorkflow.id);

    reload.resolve([
      {
        ...createdWorkflow,
        description: null,
        spec_json: null,
        updated_at: createdWorkflow.created_at,
      },
    ]);
    await flush();

    expect(router.search.sel).toBe(`workflow:${createdWorkflow.name}`);
    expect(
      container.querySelector<HTMLElement>('[data-testid="workflow-detail"]')?.dataset.workflowId,
    ).toBe(createdWorkflow.id);
  });

  it("keeps the returned id usable when the catalog reload fails", async () => {
    const reload = deferred<unknown[]>();
    await createWhileReloadIsPending(reload);

    reload.reject(new Error("catalog unavailable"));
    await flush();

    expect(router.search.sel).toBe(`workflow:${createdWorkflow.name}`);
    expect(
      container.querySelector<HTMLElement>('[data-testid="workflow-detail"]')?.dataset.workflowId,
    ).toBe(createdWorkflow.id);
  });
});
